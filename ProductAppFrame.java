    // Shared method for both the PROCESS button and Tools 
    private void processOrder() {
        try {
            String customerName = txtCustomerName.getText().trim();
            String productName = cmbProduct.getSelectedItem().toString();
            double price = Double.parseDouble(txtPrice.getText().trim());

            if (customerName.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please enter the customer's name.", "Input Error", JOptionPane.WARNING_MESSAGE);
                return;
            }

            //  calculations for ProductCalculations class
            ProductCalculations calc = new ProductCalculations(price);
            double vat = calc.GetVat();
            double commission = calc.GetCommission();
            double total = calc.GetTotal();

            // Format
            String outputMessage = "Customer Name: " + customerName + " "
                                 + "Product: " + productName + " "
                                 + "VAT: R " + vat + " "
                                 + "COMMISSION: R " + commission + " "
                                 + "TOTAL: R " + total;

            
            JOptionPane.showMessageDialog(this, outputMessage, "Message", JOptionPane.INFORMATION_MESSAGE);

            
            saveToFile(outputMessage);

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Please enter a valid numeric price.", "Invalid Input", JOptionPane.ERROR_MESSAGE);
        }
    }

    // Method to write log details to data.txt
    private void saveToFile(String details) {
        try (PrintWriter writer = new PrintWriter(new FileWriter("data.txt", true))) {
            writer.println("DATA LOG");
            writer.println("***********************************");
            writer.println(details);
            writer.println("***********************************");
        } catch (IOException ex) {
            JOptionPane.showMessageDialog(this, "Error saving to data.txt: " + ex.getMessage(), "File Error", JOptionPane.ERROR_MESSAGE);
        }
    }

